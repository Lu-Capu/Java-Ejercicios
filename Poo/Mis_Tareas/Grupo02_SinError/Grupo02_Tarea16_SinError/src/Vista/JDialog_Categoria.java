    private void btn_EliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_EliminarActionPerformed
        int fila = tbl_DatosCategoria.getSelectedRow();
        if (fila != -1) {
            int rpta = JOptionPane.showConfirmDialog(rootPane, "Desea Eliminar?");
            if (rpta == JOptionPane.YES_OPTION) {
                int idcategoria = Integer.parseInt(tbl_DatosCategoria.getValueAt(fila, 0).toString()
                );
                Elemento = new Categoria();
                Elemento.setIdcategoria(idcategoria);
                CategoriaDAO.Eliminar(Elemento);
                Actualizar_Tabla();
            }
        } else {
            JOptionPane.showMessageDialog(this, "Seleccione un registro");
        }
    }//GEN-LAST:event_btn_EliminarActionPerformed

