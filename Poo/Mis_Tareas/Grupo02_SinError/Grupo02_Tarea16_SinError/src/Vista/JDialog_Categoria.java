    private void btn_EditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_EditarActionPerformed
        Estado_Controles(true);
        int fila = tbl_DatosCategoria.getSelectedRow();
        if (fila != -1) {
            int idcategoria = Integer.parseInt(tbl_DatosCategoria.getValueAt(fila, 0).toString());
            String Nombre = tbl_DatosCategoria.getValueAt(fila, 1).toString();
            String Descripcion = tbl_DatosCategoria.getValueAt(fila, 2).toString();
            String Condicion = tbl_DatosCategoria.getValueAt(fila, 3).toString();

            Elemento = new Categoria();
            Elemento.setIdcategoria(idcategoria);
            Elemento.setNombre(Nombre);
            Elemento.setDescripcion(Descripcion);
            Elemento.setCondicion(Condicion);
            txt_Nombre.setText(Nombre);
            txt_Descripcion.setText(Descripcion);
            cmb_Condicion.setSelectedItem(Condicion);
        } else {
            JOptionPane.showMessageDialog(this, "Seleccione un registro");
        }
        Tipo_Ope = 2;
    }//GEN-LAST:event_btn_EditarActionPerformed

    private void btn_RegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_RegistrarActionPerformed
        Estado_Controles(false);
        String nombre = txt_Nombre.getText();
        String descripcion = txt_Descripcion.getText();
        String condicion = cmb_Condicion.getSelectedItem().toString();
        switch (Tipo_Ope) {
            case 1:
            Elemento = new Categoria();
            Elemento.setNombre(nombre);
            Elemento.setDescripcion(descripcion);
            Elemento.setCondicion(condicion);
            CategoriaDAO.Insertar(Elemento);
            break;
            case 2:
            Elemento.setNombre(nombre);
            Elemento.setDescripcion(descripcion);
            Elemento.setCondicion(condicion);
            CategoriaDAO.Actualizar(Elemento);
        }
        Actualizar_Tabla();
        txt_Nombre.setText("");
        txt_Descripcion.setText("");
        cmb_Condicion.setSelectedIndex(-1);
        Tipo_Ope = 0;
    }//GEN-LAST:event_btn_RegistrarActionPerformed

