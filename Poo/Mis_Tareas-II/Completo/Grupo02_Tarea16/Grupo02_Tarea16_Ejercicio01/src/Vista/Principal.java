    private void mostrarPantallaCarga() {
        JDCarga loading = new JDCarga(this, true);

        new Thread(() -> {
            try {
                Thread.sleep(2000);
                Gestor.sistemita.cargarTodoDesdeBD();
            } catch (InterruptedException e) {
                e.printStackTrace();
            } finally {
                loading.dispose();
            }
        }).start();

        loading.setVisible(true);
    }

