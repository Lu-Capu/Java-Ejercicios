    private void btn_RegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_RegistrarActionPerformed
        try {
            Estado_Controles(false);
            int idPredio = (int) spnID.getValue();
            String predio = txtPredio.getText();
            String zona = txtZona.getText();
            if (cboID.getSelectedIndex() == -1) {
                JOptionPane.showMessageDialog(null, "Debe de selecionar un codigo Asociado");
                return;
            }
            int idINVENTARIO = Integer.parseInt(cboID.getSelectedItem().toString());
            if (predio.trim().isEmpty() || zona.trim().isEmpty()) {
                JOptionPane.showMessageDialog(null, "Completar las casillas");
                return;
            }

            Predio p = new Predio(idPredio, predio, zona, idINVENTARIO);
            switch (Tipo_Ope) {
                case 1:
                    if (Gestor.sistemita.repetir(prefijo + idPredio)) {
                        Gestor.sistemita.agregarPredio("INV-" + idINVENTARIO, p);
                        objPRE.listar(table);
                    } else {
                        JOptionPane.showMessageDialog(null, "El Código se esta repitiendo\n" + "No se puede ejecutar la Operacion");
                    }
                    break;
                case 2:
                    try {
                        spnID.setEnabled(true);
                        Gestor.sistemita.editarPredio(p);
                        objPRE.listar(table);
                    } catch (Exception ex) {
                        JOptionPane.showMessageDialog(null, "Error: " + ex.getMessage());
                    }
                    break;
            }

            txtPredio.setText("");
            txtZona.setText("");
            Tipo_Ope = 0;
        } catch (Exception ex) {
            System.getLogger(JDPredio.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }//GEN-LAST:event_btn_RegistrarActionPerformed

    private void btn_EditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_EditarActionPerformed

        int fila = table.getSelectedRow();
        if (fila != -1) {
            Estado_Controles(true);
            int id = Integer.parseInt(table.getValueAt(fila, 0).toString());
            nodo = Gestor.sistemita.buscarNodo(prefijo + id);
            cargarElementos(nodo);
            spnID.setEnabled(false);
        } else {
            JOptionPane.showMessageDialog(this, "Seleccione un registro");
        }
        Tipo_Ope = 2;
    }//GEN-LAST:event_btn_EditarActionPerformed

