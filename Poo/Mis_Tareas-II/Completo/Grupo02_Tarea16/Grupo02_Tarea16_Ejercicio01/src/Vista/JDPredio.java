    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        try {
            String id = JOptionPane.showInputDialog("Ingresar dato");
            Nodo p = Gestor.sistemita.buscarNodo(prefijo + id);
            if (p == null) {
                txtArea.setText("");
                JOptionPane.showMessageDialog(null, "No se encontro al Predio con ID: " + id);
                return;
            }
            Predio pre = (Predio) p.getDato();
            txtArea.setText("=======PREDIO======\n"
                    + "Clave: " + pre.getIdPredio() + "\n"
                    + "Predio: " + pre.getPredio() + "\n"
                    + "Zona : " + pre.getZona() + "\n"
                    + "Coidgo de Inventario: " + pre.getCodigoInventario());
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error:" + e.getMessage());
        }


    }//GEN-LAST:event_btnBuscarActionPerformed

