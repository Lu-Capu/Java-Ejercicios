    private void btn_EliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_EliminarActionPerformed
        int fila = table.getSelectedRow();
        if (fila != -1) {
            int rpta = JOptionPane.showConfirmDialog(rootPane, "Desea Eliminar?");
            if (rpta == JOptionPane.YES_OPTION) {
                int idPredio = Integer.parseInt(table.getValueAt(fila, 0).toString());
                nodo = Gestor.sistemita.buscarNodo(prefijo + idPredio);
                if (nodo == null) {
                    JOptionPane.showMessageDialog(null, "No se puede Eliminar");
                    return;
                }
                Predio pre = (Predio) nodo.getDato();
                Gestor.sistemita.eliminarPredio(pre);
                try {
                    objPRE.listar(table);
                } catch (Exception ex) {

                }
            }
        } else {
            JOptionPane.showMessageDialog(this, "Seleccione un registro");
        }
    }//GEN-LAST:event_btn_EliminarActionPerformed

