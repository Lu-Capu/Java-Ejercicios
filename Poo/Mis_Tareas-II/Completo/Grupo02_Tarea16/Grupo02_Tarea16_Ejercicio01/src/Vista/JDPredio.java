    private void cargarElementos(Nodo<Object> actual) {
        if (actual != null) {
            Predio obj = (Predio) nodo.getDato();
            spnID.setValue(obj.getIdPredio());
            txtPredio.setText(obj.getPredio());
            txtZona.setText(obj.getZona());
            cboID.setSelectedItem(obj.getCodigoInventario() + "");
            nodo = actual;
        }
    }

